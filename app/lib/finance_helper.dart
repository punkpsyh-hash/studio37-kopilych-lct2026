String _norm(String s) => s
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replaceAll(RegExp(r'[^\p{L}\p{N}\s]', unicode: true), ' ');

List<String> _words(String s) =>
    [for (final w in _norm(s).split(RegExp(r'\s+'))) if (w.length > 2) w];

Set<String> _trigrams(String w) {
  final p = ' $w ';
  return {for (var i = 0; i + 3 <= p.length; i++) p.substring(i, i + 3)};
}

/// Сходство слов 0..1: общее начало (5 букв) или коэффициент Дайса по триграммам.
/// Короткие слова (пин, смс, код) — только точное совпадение, чтобы не путать.
double _wordSim(String a, String b) {
  if (a == b) return 1;
  if (a.length <= 3 || b.length <= 3) return 0;
  const n = 5;
  if (a.length >= n && b.length >= n && a.substring(0, n) == b.substring(0, n)) {
    return 1;
  }
  final ta = _trigrams(a), tb = _trigrams(b);
  return 2 * ta.intersection(tb).length / (ta.length + tb.length);
}

const _minWordSim = 0.6;

/// Оценка ключа: каждое его слово должно найтись в вопросе; 0 — не подошёл.
double _keyScore(List<String> keyWords, List<String> queryWords) {
  var total = 0.0;
  for (final k in keyWords) {
    var best = 0.0;
    for (final q in queryWords) {
      final s = _wordSim(k, q);
      if (s > best) best = s;
    }
    if (best < _minWordSim) return 0;
    total += best;
  }
  return total;
}

/// Выбирает ответ по вопросу ребёнка. Ничего не генерирует.
HelperAnswer answerFinanceQuestion(String question) {
  final normalized = _norm(question);
  for (final (pattern, text) in _danger) {
    if (RegExp(pattern, unicode: true).hasMatch(normalized)) {
      return HelperAnswer('danger', text);
    }
  }
  final qw = _words(question);
  HelperCard? best;
  var score = 0.0;
  for (final card in helperCards) {
    for (final key in card.keys) {
      final kw = _words(key);
      if (kw.isEmpty) continue;
      final s = _keyScore(kw, qw);
      if (s > score) {
        best = card;
        score = s;
      }
    }
  }
  return best == null
      ? const HelperAnswer('parents', _parentsText)
      : HelperAnswer(best.id, best.text);
}
