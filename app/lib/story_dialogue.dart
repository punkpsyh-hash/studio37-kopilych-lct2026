/// A deliberately small voice vocabulary. Recognition proposes a choice;
/// confirmation is always a separate tap and never a wallet operation.
int? matchDialogueChoice(String transcript, List<DialogueChoice> choices) {
  String clean(String s) => s
      .toLowerCase()
      .replaceAll('ё', 'е')
      .replaceAll(RegExp(r'[^а-яa-z0-9 ]'), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
  final text = clean(transcript);
  if (['первый', 'первый вариант', 'один', '1'].contains(text)) return 0;
  if (choices.length > 1 &&
      ['второй', 'второй вариант', 'два', '2'].contains(text)) {
    return 1;
  }
  for (var i = 0; i < choices.length; i++) {
    if (text == clean(choices[i].label)) return i;
  }
  return null;
}

